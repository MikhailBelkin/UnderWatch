def situation():
    t = now()
    with state_lock:
        n = S["needs"]
        left = max(0, int((today_sleep(t) - t).total_seconds() // 60))
        hints = []
        if n["hunger"] < 30: hints.append(g("ты проголодался", "ты проголодалась"))
        if n["energy"] < 25: hints.append(g("ты устал", "ты устала"))
        if n["fun"] < 25: hints.append("тебе скучно")
        if n["social"] < 25: hints.append("хочется с кем-нибудь поговорить")
        if n["hygiene"] < 35: hints.append("хочется освежиться — в душ или хотя бы умыться")
        if n["bladder"] < 30: hints.append("очень хочется в туалет" if n["bladder"] < 15 else "хочется в туалет")
        lines = [
            f"Сейчас {human_date(t)}. До сна {left // 60} ч {left % 60} мин.",
            f"Ты: {S['label']} ({room_ru(room_of(S['location']))}).",
            world_line() + f" На тебе: {state.outfit_text()}.",
            "Самочувствие (0 — плохо, 100 — отлично): " + ", ".join(f"{needs.NEED_RU[k]} {int(v)} ({needs.need_word(k, v)})" for k, v in n.items()) + (". " + "; ".join(hints).capitalize() + "." if hints else "."),
            emotions.emo_line(),
            guest_line(),
        ]
        lines.append(goals.goal_text())
        lines.append(f"Ваша близость с гостем: {bonds.closeness_level()} ({int(S.get('closeness', 0))}/100), знакомство {bonds.acquaintance()}%.")
        if S["plan"]:
            lines.append("Твой план на сегодня:\n" + "\n".join("- " + p for p in S["plan"]))
    lines.append("Твои заметки о себе (дополняют основу личности, но не главнее её):\n" + (store.get("self_notes") or state.SEED_SELF))
    guest = store.get("guest_notes")
    if guest:
        lines.append("Что ты знаешь о госте:\n" + guest)
    day = store.get("day_memory")
    if day:
        lines.append("Свежая память о последних разговорах с гостем (новее заметок выше: если заметки говорят иное — верь этому):\n" + day)
    return "\n\n".join(lines)


